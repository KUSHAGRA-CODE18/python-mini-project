def add(a, b):
    return a + b 

def subtract(a, b):
    return a - b 
def multiply(a, b):
    return a * b

num1 = int(input("Enter the 1st number :")) 
num2 = int(input("Enter the 2nd number :"))
print("Addition:", add(num1, num2)) 
print("Subtraction:", subtract(num1, num2))
print("Multiplication:", multiply(num1, num2))